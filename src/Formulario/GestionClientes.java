    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
     String cedula = txtCedula.getText();
    String nombre = txtNombre.getText();
    String telefono = txtTelefono.getText();
    String correo = txtCorreo.getText();
    String direccion = txtDireccion.getText();
    String fechaRegistro = txtFechaRegistro.getText();
    boolean estado = chkEstado.isSelected();

    // Validar campos vacíos
    if (cedula.isEmpty() || nombre.isEmpty() || telefono.isEmpty()
            || correo.isEmpty() || direccion.isEmpty()
            || fechaRegistro.isEmpty()) {

        JOptionPane.showMessageDialog(this, "Complete todos los campos");
        return;
    }

    // Validar teléfono
    if (!telefono.matches("[0-9]+")) {
        JOptionPane.showMessageDialog(this,
                "El teléfono debe contener solo números");
        return;
    }

    // Validar correo
    if (!correo.contains("@")) {
        JOptionPane.showMessageDialog(this,
                "Ingrese un correo válido");
        return;
    }

    // Obtener el modelo de la tabla
    DefaultTableModel modelo =
            (DefaultTableModel) tablaClientes.getModel();

    // Crear el cliente
    Cliente cliente = new Cliente(
            cedula,
            nombre,
            telefono,
            correo,
            direccion,
            fechaRegistro,
            estado
    );
    listaClientes.add(cliente);


    // Agregar el cliente a la tabla
    modelo.addRow(new Object[]{
        cedula,
        nombre,
        telefono,
        correo,
        direccion,
        fechaRegistro,
        estado ? "Activo" : "Inactivo"
    });

    // Mensaje
    JOptionPane.showMessageDialog(this,
            "Cliente guardado correctamente");

    // Limpiar campos
    txtCedula.setText("");
    txtNombre.setText("");
    txtTelefono.setText("");
    txtCorreo.setText("");
    txtDireccion.setText("");
    txtFechaRegistro.setText("");
    chkEstado.setSelected(false);

    }//GEN-LAST:event_btnGuardarActionPerformed

