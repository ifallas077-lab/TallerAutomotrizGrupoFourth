    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int fila = tablaClientes.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un cliente de la tabla");
            return;
        }
        tablaClientes.setValueAt(txtCedula.getText(), fila, 0);
        tablaClientes.setValueAt(txtNombre.getText(), fila, 1);
        tablaClientes.setValueAt(txtTelefono.getText(), fila, 2);
        tablaClientes.setValueAt(txtCorreo.getText(), fila, 3);
        tablaClientes.setValueAt(txtDireccion.getText(), fila, 4);
        tablaClientes.setValueAt(txtFechaRegistro.getText(), fila, 5);
        tablaClientes.setValueAt(chkEstado.isSelected() ? "Activo" : "Inactivo", fila, 6);
        JOptionPane.showMessageDialog(this, "Cliente editado correctamente");

        txtCedula.setText("");
        txtNombre.setText("");
        txtTelefono.setText("");
        txtCorreo.setText("");
        txtDireccion.setText("");
        txtFechaRegistro.setText("");
        chkEstado.setSelected(false);
        tablaClientes.clearSelection();
    }//GEN-LAST:event_btnEditarActionPerformed

