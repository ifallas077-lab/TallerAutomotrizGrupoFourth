    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
       
    int fila = tablaTecnicos.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this, "Seleccione un técnico de la tabla");
        return;
    }

    int respuesta = JOptionPane.showConfirmDialog(
            this,
            "¿Está seguro de que desea eliminar este técnico?",
            "Confirmar eliminación",
            JOptionPane.YES_NO_OPTION
    );

    if (respuesta == JOptionPane.YES_OPTION) {
        listaTecnicos.remove(fila);

        DefaultTableModel modeloTabla =
                (DefaultTableModel) tablaTecnicos.getModel();

        modeloTabla.removeRow(fila);

        JOptionPane.showMessageDialog(this, "Técnico eliminado correctamente");
    }

    }//GEN-LAST:event_btnEliminarActionPerformed

