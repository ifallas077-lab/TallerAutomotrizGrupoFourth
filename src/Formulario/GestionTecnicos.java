    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

if (txtCedula.getText().trim().isEmpty()
        || txtNombre.getText().trim().isEmpty()
        || txtTelefono.getText().trim().isEmpty()
        || txtCorreo.getText().trim().isEmpty()
        || txtEspecialidad.getText().trim().isEmpty()) {

    JOptionPane.showMessageDialog(
            this, "Debe completar todos los campos");
    return;
}

String cedula = txtCedula.getText().trim();
String nombre = txtNombre.getText().trim();
String telefono = txtTelefono.getText().trim();
String correo = txtCorreo.getText().trim();
String especialidad = txtEspecialidad.getText().trim();

if (!telefono.matches("[0-9]+")) {
    JOptionPane.showMessageDialog(
            this, "El teléfono debe contener solo números");
    return;
}

if (!correo.contains("@")) {
    JOptionPane.showMessageDialog(
            this, "Ingrese un correo válido");
    return;
}

for (Mecanico mecanico : listaTecnicos) {
    if (mecanico.getCedula().equals(cedula)) {
        JOptionPane.showMessageDialog(
                this, "Ya existe un técnico con esa cédula");
        return;
    }
}

boolean estado = chkEstado.isSelected();

Mecanico mecanico = new Mecanico();

mecanico.setCedula(cedula);
mecanico.setNombre(nombre);
mecanico.setTelefono(telefono);
mecanico.setCorreo(correo);
mecanico.setEspecialidad(especialidad);
mecanico.setEstado(estado);

listaTecnicos.add(mecanico);

DefaultTableModel modeloTabla =
        (DefaultTableModel) tablaTecnicos.getModel();

modeloTabla.addRow(new Object[]{
    mecanico.getCedula(),
    mecanico.getNombre(),
    mecanico.getTelefono(),
    mecanico.getCorreo(),
    mecanico.getEspecialidad(),
    "",
    mecanico.isEstado() ? "Activo" : "Inactivo"
});

JOptionPane.showMessageDialog(
        this, "Técnico guardado correctamente");

     
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed

String cedula = txtCedula.getText().trim();

if (cedula.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Ingrese la cédula del técnico que desea buscar");
    return;
}

boolean encontrado = false;

for (Mecanico mecanico : listaTecnicos) {
    if (mecanico.getCedula().equals(cedula)) {

        txtNombre.setText(mecanico.getNombre());
        txtTelefono.setText(mecanico.getTelefono());
        txtCorreo.setText(mecanico.getCorreo());
        txtEspecialidad.setText(mecanico.getEspecialidad());
        chkEstado.setSelected(mecanico.isEstado());

        encontrado = true;
        break;
    }
}

if (encontrado == false) {
    JOptionPane.showMessageDialog(this, "No se encontró un técnico con esa cédula");
}
    }//GEN-LAST:event_btnBuscarActionPerformed

