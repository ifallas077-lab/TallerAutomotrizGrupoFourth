    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
       
int fila = tablaTecnicos.getSelectedRow();

if (fila == -1) {
    JOptionPane.showMessageDialog(this, "Seleccione un técnico de la tabla");
    return;
}

String cedula = txtCedula.getText().trim();
String nombre = txtNombre.getText().trim();
String telefono = txtTelefono.getText().trim();
String correo = txtCorreo.getText().trim();
String especialidad = txtEspecialidad.getText().trim();

if (cedula.isEmpty() || nombre.isEmpty()
        || telefono.isEmpty() || correo.isEmpty()
        || especialidad.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Debe completar todos los campos");
    return;
}

if (!telefono.matches("[0-9]+")) {
    JOptionPane.showMessageDialog(this, "El teléfono debe contener solo números");
    return;
}

if (!correo.contains("@")) {
    JOptionPane.showMessageDialog(this, "Ingrese un correo válido");
    return;
}

Mecanico mecanico = listaTecnicos.get(fila);

mecanico.setCedula(cedula);
mecanico.setNombre(nombre);
mecanico.setTelefono(telefono);
mecanico.setCorreo(correo);
mecanico.setEspecialidad(especialidad);
mecanico.setEstado(chkEstado.isSelected());

DefaultTableModel modeloTabla =
        (DefaultTableModel) tablaTecnicos.getModel();

modeloTabla.setValueAt(cedula, fila, 0);
modeloTabla.setValueAt(nombre, fila, 1);
modeloTabla.setValueAt(telefono, fila, 2);
modeloTabla.setValueAt(correo, fila, 3);
modeloTabla.setValueAt(especialidad, fila, 4);
modeloTabla.setValueAt(
        chkEstado.isSelected() ? "Activo" : "Inactivo", fila, 6);

JOptionPane.showMessageDialog(this, "Técnico actualizado correctamente");

    }//GEN-LAST:event_btnEditarActionPerformed

