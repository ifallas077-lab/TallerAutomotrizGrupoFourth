    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed

    if (txtPlaca.getText().trim().isEmpty()
            || txtMarca.getText().trim().isEmpty()
            || txtModelo.getText().trim().isEmpty()
            || txtAnio.getText().trim().isEmpty()
            || txtKilometraje.getText().trim().isEmpty()
            || txtTipo.getText().trim().isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Debe completar todos los campos"
        );
        return;
    }

    String placa = txtPlaca.getText();
    String marca = txtMarca.getText();
    String modelo = txtModelo.getText();
    String tipo = txtTipo.getText();

    int anio;
    double kilometraje;

    try {
        anio = Integer.parseInt(txtAnio.getText().trim());
        kilometraje = Double.parseDouble(txtKilometraje.getText().trim());

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "El año y el kilometraje deben ser números válidos"
        );
        return;
    }
 boolean estado = chkEstado.isSelected();

    Vehiculo vehiculo = new Vehiculo();

    vehiculo.setPlaca(placa);
    vehiculo.setMarca(marca);
    vehiculo.setModelo(modelo);
    vehiculo.setAnio(anio);
    vehiculo.setKilometraje(kilometraje);
    vehiculo.setTipo(tipo);
    vehiculo.setEstado(estado);
    
    listaVehiculos.add(vehiculo);
DefaultTableModel modeloTabla= (DefaultTableModel) tablaVehiculos.getModel();

modeloTabla.addRow(new Object[]{
    vehiculo.getPlaca(),
    vehiculo.getMarca(),
    vehiculo.getModelo(),
    vehiculo.getAnio(),
    vehiculo.getKilometraje(),
    vehiculo.getTipo(),
    vehiculo.isEstado() ? "Activo" : "Inactivo"
});

javax.swing.JOptionPane.showMessageDialog(
        this,
        "Vehículo guardado correctamente"
);
      
    }//GEN-LAST:event_btnGuardarActionPerformed

