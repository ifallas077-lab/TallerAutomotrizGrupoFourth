    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
String placaBuscar = txtPlaca.getText().trim();

if (placaBuscar.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Ingrese una placa para buscar");
    return;
}

for (Vehiculo vehiculo : listaVehiculos) {

    if (vehiculo.getPlaca().equalsIgnoreCase(placaBuscar)) {

        txtPlaca.setText(vehiculo.getPlaca());
        txtMarca.setText(vehiculo.getMarca());
        txtModelo.setText(vehiculo.getModelo());
        txtAnio.setText(String.valueOf(vehiculo.getAnio()));
        txtKilometraje.setText(String.valueOf(vehiculo.getKilometraje()));
        txtTipo.setText(vehiculo.getTipo());
        chkEstado.setSelected(vehiculo.isEstado());

        int fila = listaVehiculos.indexOf(vehiculo);
        tablaVehiculos.setRowSelectionInterval(fila, fila);

        javax.swing.JOptionPane.showMessageDialog(
                this, "Vehículo encontrado correctamente");
        return;
    }
}

javax.swing.JOptionPane.showMessageDialog(
        this, "No se encontró ningún vehículo con esa placa");
   
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
          int fila = tablaVehiculos.getSelectedRow();

    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Primero busque o seleccione un vehículo");
        return;
    }

    if (txtPlaca.getText().trim().isEmpty()
            || txtMarca.getText().trim().isEmpty()
            || txtModelo.getText().trim().isEmpty()
            || txtAnio.getText().trim().isEmpty()
            || txtKilometraje.getText().trim().isEmpty()
            || txtTipo.getText().trim().isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
                this, "Debe completar todos los campos");
        return;
    }

    int anio;
    double kilometraje;

    try {
        anio = Integer.parseInt(txtAnio.getText().trim());
        kilometraje = Double.parseDouble(txtKilometraje.getText().trim());
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "El año y el kilometraje deben ser números válidos");
        return;
    }

    int posicion = tablaVehiculos.convertRowIndexToModel(fila);

    Vehiculo vehiculo = listaVehiculos.get(posicion);

    vehiculo.setPlaca(txtPlaca.getText().trim());
    vehiculo.setMarca(txtMarca.getText().trim());
    vehiculo.setModelo(txtModelo.getText().trim());
    vehiculo.setAnio(anio);
    vehiculo.setKilometraje(kilometraje);
    vehiculo.setTipo(txtTipo.getText().trim());
    vehiculo.setEstado(chkEstado.isSelected());

    DefaultTableModel modeloTabla =
            (DefaultTableModel) tablaVehiculos.getModel();

    modeloTabla.setValueAt(vehiculo.getPlaca(), posicion, 0);
    modeloTabla.setValueAt(vehiculo.getMarca(), posicion, 1);
    modeloTabla.setValueAt(vehiculo.getModelo(), posicion, 2);
    modeloTabla.setValueAt(vehiculo.getAnio(), posicion, 3);
    modeloTabla.setValueAt(vehiculo.getKilometraje(), posicion, 4);
    modeloTabla.setValueAt(vehiculo.getTipo(), posicion, 5);
    modeloTabla.setValueAt(
            vehiculo.isEstado() ? "Activo" : "Inactivo",
            posicion, 6);

    javax.swing.JOptionPane.showMessageDialog(
            this, "Vehículo actualizado correctamente");


    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed

    int fila = tablaVehiculos.getSelectedRow();

    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Seleccione un vehículo para eliminar");
        return;
    }

    int respuesta = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "¿Está seguro de eliminar este vehículo?",
            "Confirmar eliminación",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (respuesta != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    int posicion = tablaVehiculos.convertRowIndexToModel(fila);

    listaVehiculos.remove(posicion);

    DefaultTableModel modeloTabla =
            (DefaultTableModel) tablaVehiculos.getModel();

    modeloTabla.removeRow(posicion);

    txtPlaca.setText("");
    txtMarca.setText("");
    txtModelo.setText("");
    txtAnio.setText("");
    txtKilometraje.setText("");
    txtTipo.setText("");
    chkEstado.setSelected(false);

    tablaVehiculos.clearSelection();

    javax.swing.JOptionPane.showMessageDialog(
            this, "Vehículo eliminado correctamente");

    }//GEN-LAST:event_btnEliminarActionPerformed

